"""Owned runtime selection and validated generic workflow dispatch."""

from dataclasses import dataclass, field
import json
from pathlib import Path
import tempfile
from typing import Any
from uuid import UUID, uuid4

from jsonschema import Draft202012Validator

from ..context import owned_context, PackageContext
from ..storage import VersionStorage
from .model_channel import model_channel
from .fetch import PublicFetch, declared_public_urls, declared_public_queries
from .preparation import ensure_current_worker_code
from .sandbox import WorkerLimits, WorkerUnavailable
from .transport import invoke_worker


@dataclass(frozen=True)
class PackageRuntime:
    context: PackageContext
    storage: VersionStorage
    manifest: dict[str, Any]
    image: str
    source_documents: dict[str, bytes] = field(default_factory=dict, repr=False)

    def workflow(self, identity):
        found = next(
            (
                row
                for row in self.manifest["runtime"]["workflows"]
                if row["id"] == identity
            ),
            None,
        )
        if found is None:
            raise WorkerUnavailable(
                "workflow is not registered in the selected version"
            )
        return found

    def execute(
        self,
        workflow_id,
        *,
        inputs,
        run_id,
        selected_model=None,
        network_authority=False,
        on_event=None,
        cancelled=None,
        completion=None,
        limits=None,
    ):
        """Execute a registered workflow with an already-owned model connection."""
        if not isinstance(run_id, UUID):
            raise ValueError("run identity must be generated by the host")
        workflow = self.workflow(workflow_id)
        # Package requests remain bounded by host ceilings. Explicit caller
        # limits override package defaults, including tests and cancellation.
        metadata = workflow.get("metadata", {})
        if limits is None:
            requested = metadata.get("timeout_seconds", 1800)
            if (
                not isinstance(requested, int)
                or isinstance(requested, bool)
                or not 1 <= requested <= 7200
            ):
                raise WorkerUnavailable("workflow timeout exceeds the host limit")
            limits = WorkerLimits(timeout_seconds=requested)
        model_timeout = metadata.get("model_timeout_seconds", 120)
        if (
            not isinstance(model_timeout, int)
            or isinstance(model_timeout, bool)
            or not 1 <= model_timeout <= 1800
        ):
            raise WorkerUnavailable("model timeout exceeds the host limit")
        Draft202012Validator(workflow["input_schema"]).validate(inputs)
        output = self.storage.run_root(self.context, run_id)
        output.mkdir(parents=True, exist_ok=False)
        request = {
            "contract_version": 1,
            "request_id": str(run_id),
            "operation": "execute",
            "workflow_id": workflow_id,
            "hook_id": None,
            "input": {"inputs": inputs},
            "authority": {
                "network": network_authority,
                "model_access": selected_model is not None,
            },
        }
        fetch = (
            PublicFetch(
                declared_public_urls(self),
                queries=declared_public_queries(self, workflow),
                timeout=min(120, limits.timeout_seconds),
            )
            if network_authority
            else None
        )
        try:
            result = invoke_worker(
                image=self.image,
                package_root=self.storage.version_root(self.context),
                run_root=output,
                manifest=self.manifest,
                request=request,
                model_handler=(
                    model_channel(
                        selected_model,
                        completion=completion,
                        timeout_seconds=min(model_timeout, limits.timeout_seconds),
                    )
                    if selected_model
                    else None
                ),
                model_snapshot=selected_model.safe_snapshot if selected_model else None,
                fetch_handler=fetch,
                on_event=on_event,
                cancelled=cancelled,
                limits=limits,
            )
        finally:
            if fetch is not None:
                fetch.close()
        if result["status"] == "succeeded":
            Draft202012Validator(workflow["output_schema"]).validate(result["result"])
            typed = result["result"]["structured_value"].get("typed_report")
            if (
                workflow.get("metadata", {}).get("output_format")
                == "prism-typed-report/v1"
                or typed is not None
            ):
                from prism_stdlib.report_codec import decode_report

                decode_report(typed, attachments={})
            verification = result["result"]["report_verification"]
            if (workflow["verify_hook"] is not None or verification is not None) and (
                verification or {}
            ).get("status") != "passed":
                raise WorkerUnavailable("package report verification did not pass")
        return result

    def policy(self, hook_id, operation, inputs):
        return self._policy(hook_id, {"operation": operation, "input": inputs})

    def policy_many(self, hook_id, calls):
        return self._policy(hook_id, {"policy_calls": calls})

    def _policy(self, hook_id, inputs):
        """Evaluate declared read-only policy in a disposable isolated container."""
        if hook_id not in self.manifest["runtime"]["planning_hooks"]:
            raise WorkerUnavailable(
                "policy hook is not registered in the selected version"
            )
        parent = self.storage.version_root(self.context) / "policy-work"
        parent.mkdir(exist_ok=True)
        with tempfile.TemporaryDirectory(prefix="policy-", dir=parent) as raw:
            request = {
                "contract_version": 1,
                "request_id": uuid4().hex,
                "operation": "plan",
                "workflow_id": None,
                "hook_id": hook_id,
                "input": inputs,
                "authority": {"network": False, "model_access": False},
            }
            result = invoke_worker(
                image=self.image,
                package_root=self.storage.version_root(self.context),
                run_root=Path(raw),
                manifest=self.manifest,
                request=request,
                limits=WorkerLimits(
                    timeout_seconds=120, request_bytes=128 * 1024 * 1024
                ),
            )
            if result["status"] != "succeeded":
                raise WorkerUnavailable("selected-package policy evaluation failed")
            if result["artifacts"]:
                raise WorkerUnavailable(
                    "planning policy attempted to create persistent artifacts"
                )
            return result["result"]["structured_value"]["policy_value"]


async def load_runtime(connection, user_id, version_id, storage):
    """Read one ready owned image; never prepare dependencies as a fallback."""
    context = await owned_context(connection, user_id, version_id)
    row = await connection.fetchrow(
        "SELECT manifest,runtime_state,runtime_image FROM package_versions WHERE id=$1 AND user_id=$2",
        context.version_id,
        user_id,
    )
    if row["runtime_state"] != "ready" or not row["runtime_image"]:
        raise WorkerUnavailable(
            "Prepare the selected package runtime before execution or policy evaluation"
        )
    image = await ensure_current_worker_code(connection, context)
    manifest = (
        json.loads(row["manifest"])
        if isinstance(row["manifest"], str)
        else row["manifest"]
    )
    from ..source_workflows import runtime_manifest

    manifest = runtime_manifest(manifest, storage.version_root(context))
    paths = [
        resource["document"] for resource in manifest["collections"]["data-sources"]
    ]
    documents = await connection.fetch(
        "SELECT path,payload FROM package_files WHERE user_id=$1 AND version_id=$2 AND storage_kind='database' AND path=ANY($3::text[])",
        user_id,
        context.version_id,
        paths,
    )
    return PackageRuntime(
        context,
        storage,
        manifest,
        image,
        {document["path"]: document["payload"] for document in documents},
    )
