"""Atomic, snapshot-validated ZIP writing for owned Lunar package exports.

The exporter copies explicitly selected source bytes into a private snapshot,
validates resource relationships with the pinned format, and publishes one ZIP.
It neither imports an application nor changes the source database or files.
"""

from __future__ import annotations

from collections.abc import Iterator, Mapping
import hashlib
import json
import mimetypes
import os
from pathlib import Path
import stat
import sys
import tempfile
from typing import Any
import zipfile

from .format.contract import (
    COLLECTIONS,
    archive_path,
    validate_document,
    validate_payloads,
)


class ExportError(ValueError):
    """The requested source snapshot cannot produce a complete portable archive."""


def json_bytes(value: Any) -> bytes:
    """Encode deterministic finite JSON for a resource or manifest document."""
    return (
        json.dumps(value, sort_keys=True, indent=2, ensure_ascii=False, allow_nan=False)
        + "\n"
    ).encode()


def _stamp(path: Path) -> tuple[int, ...]:
    """Identify one regular source file without following a final symlink."""
    info = path.lstat()
    if not stat.S_ISREG(info.st_mode):
        raise ExportError(f"export input must be a regular file: {path}")
    return (info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns)


class SnapshotPayloads(Mapping[str, bytes]):
    """Expose one payload at a time to the shared format validator."""

    def __init__(self, root: Path, names: Mapping[str, Any]):
        """Bind the private snapshot and its exact declared file inventory."""
        self.root, self.names = root, names

    def __iter__(self) -> Iterator[str]:
        """Iterate the declared payload identities in deterministic order."""
        return iter(sorted(self.names))

    def __len__(self) -> int:
        """Return the number of declared regular payload files."""
        return len(self.names)

    def __getitem__(self, key: str) -> bytes:
        """Read one declared snapshot payload without exposing other paths."""
        if key not in self.names:
            raise KeyError(key)
        return (self.root / key).read_bytes()


class ArchiveBuilder:
    """Collect immutable resource bytes and atomically publish a validated ZIP."""

    def __init__(self, snapshot: Path, *, package_key: str, display_name: str):
        """Initialize the private snapshot and empty portable collections."""
        snapshot.mkdir(parents=True, exist_ok=False)
        self.root = snapshot.resolve(strict=True)
        self.files: dict[str, dict[str, Any]] = {}
        self.sources: dict[Path, tuple[int, ...]] = {}
        self.manifest: dict[str, Any] = {
            "format_version": 1,
            "package": {"key": package_key, "display_name": display_name},
            "runtime": {
                "contract_version": 1,
                "python": ">=3.12,<3.14",
                "requirements_lock": None,
                "entrypoints": [],
                "planning_hooks": [],
            },
            "collections": {kind: [] for kind in COLLECTIONS},
            "files": [],
        }

    def add_bytes(
        self, path: str, content: bytes, *, media_type: str | None = None
    ) -> str:
        """Store generated bytes once, rejecting inconsistent duplicate paths."""
        path = archive_path(path)
        digest = hashlib.sha256(content).hexdigest()
        if path in self.files:
            if self.files[path]["sha256"] != digest or self.files[path]["size"] != len(
                content
            ):
                raise ExportError(f"conflicting payload identity: {path}")
            return path
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        self.files[path] = {
            "path": path,
            "size": len(content),
            "sha256": digest,
            "media_type": media_type
            or mimetypes.guess_type(path)[0]
            or "application/octet-stream",
        }
        return path

    def add_file(
        self,
        path: str,
        source: Path,
        *,
        source_root: Path,
        expected_digest: str | None = None,
        rendered: bytes | None = None,
    ) -> str:
        """Snapshot a confined source file and reject missing, changed or corrupt input."""
        path = archive_path(path)
        source, source_root = source.absolute(), source_root.resolve(strict=True)
        try:
            source.relative_to(source_root)
            for part in (source, *source.parents):
                if part == source_root:
                    break
                if part.is_symlink():
                    raise ExportError(
                        f"export input cannot traverse a symlink: {source}"
                    )
            before = _stamp(source)
        except (OSError, ValueError) as exc:
            raise ExportError(f"missing or unconfined export input: {source}") from exc
        if source in self.sources and self.sources[source] != before:
            raise ExportError(f"export input changed: {source}")
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        digest = hashlib.sha256()
        size = 0
        # A private temporary payload avoids replacing an existing inventory row
        # before duplicate identity and source snapshot checks have passed.
        with tempfile.NamedTemporaryFile(dir=target.parent, delete=False) as output:
            temporary = Path(output.name)
            try:
                with source.open("rb") as stream:
                    for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                        digest.update(chunk)
                        size += len(chunk)
                        output.write(chunk)
                if _stamp(source) != before or size != before[2]:
                    raise ExportError(f"export input changed while copying: {source}")
                actual = digest.hexdigest()
                if (
                    expected_digest is not None
                    and actual != expected_digest.removeprefix("sha256:")
                ):
                    raise ExportError(f"export input digest mismatch: {source}")
                self.sources[source] = before
            except BaseException:
                temporary.unlink(missing_ok=True)
                raise
        try:
            if rendered is not None:
                return self.add_bytes(path, rendered)
            if path in self.files:
                if (
                    self.files[path]["sha256"] != actual
                    or self.files[path]["size"] != size
                ):
                    raise ExportError(f"conflicting payload identity: {path}")
                return path
            temporary.replace(target)
            self.files[path] = {
                "path": path,
                "size": size,
                "sha256": actual,
                "media_type": mimetypes.guess_type(path)[0]
                or "application/octet-stream",
            }
            return path
        finally:
            temporary.unlink(missing_ok=True)

    def add_resource(
        self,
        kind: str,
        document: dict[str, Any],
        *,
        files: list[str] | None = None,
        references: list[dict[str, str]] | None = None,
    ) -> None:
        """Register a schema-validated collection document with its logical closure."""
        validate_document(document, kind)
        if any(
            row["id"] == document["id"] for row in self.manifest["collections"][kind]
        ):
            raise ExportError(f'duplicate {kind} identity: {document["id"]}')
        # Logical IDs permit colons; hashed document filenames remain portable
        # on every supported filesystem without changing logical identity.
        name = hashlib.sha256(document["id"].encode()).hexdigest()
        path = self.add_bytes(
            f"{kind}/documents/{name}.json",
            json_bytes(document),
            media_type="application/json",
        )
        self.manifest["collections"][kind].append(
            {
                "id": document["id"],
                "document": path,
                "files": sorted(set(files or [])),
                "references": references or [],
            }
        )

    def verify_sources(self) -> None:
        """Reject any source file replaced or modified since it was snapshotted."""
        for source, expected in self.sources.items():
            try:
                actual = _stamp(source)
            except OSError as exc:
                raise ExportError(f"export input disappeared: {source}") from exc
            if actual != expected:
                raise ExportError(f"export input changed before publication: {source}")

    def publish(self, destination: Path) -> dict[str, Any]:
        """Validate the snapshot and atomically create a new deterministic ZIP."""
        destination = destination.absolute()
        if destination.exists():
            raise ExportError(f"export destination already exists: {destination}")
        destination.parent.mkdir(parents=True, exist_ok=True)
        self.manifest["files"] = [self.files[path] for path in sorted(self.files)]
        for resources in self.manifest["collections"].values():
            resources.sort(key=lambda row: row["id"])
        self.verify_sources()
        validate_payloads(
            self.manifest,
            SnapshotPayloads(self.root, self.files),
            python_version=f"{sys.version_info.major}.{sys.version_info.minor}",
        )
        descriptor, filename = tempfile.mkstemp(
            prefix="." + destination.name + ".", suffix=".tmp", dir=destination.parent
        )
        os.close(descriptor)
        temporary = Path(filename)
        try:
            with zipfile.ZipFile(
                temporary,
                "w",
                compression=zipfile.ZIP_DEFLATED,
                compresslevel=6,
                allowZip64=True,
            ) as archive:
                for name in (
                    "manifest.json",
                    *(kind + "/" for kind in COLLECTIONS),
                    *sorted(self.files),
                ):
                    info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
                    info.create_system = 3
                    info.external_attr = (
                        (stat.S_IFDIR | 0o755)
                        if name.endswith("/")
                        else (stat.S_IFREG | 0o644)
                    ) << 16
                    info.compress_type = zipfile.ZIP_DEFLATED
                    if name == "manifest.json":
                        archive.writestr(info, json_bytes(self.manifest))
                    elif name.endswith("/"):
                        archive.writestr(info, b"")
                    else:
                        with (
                            archive.open(info, "w", force_zip64=True) as output,
                            (self.root / name).open("rb") as source,
                        ):
                            for chunk in iter(lambda: source.read(1024 * 1024), b""):
                                output.write(chunk)
            self.verify_sources()
            with temporary.open("rb") as stream:
                os.fsync(stream.fileno())
            # Hard-link publication is atomic and refuses a competing writer's
            # destination instead of replacing an existing export.
            os.link(temporary, destination)
        finally:
            temporary.unlink(missing_ok=True)
        return self.manifest
